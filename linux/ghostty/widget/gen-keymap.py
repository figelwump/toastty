#!/usr/bin/env python3
"""Generate the widget's key translation tables from the pinned Ghostty sources.

Ghostty's GTK apprt derives the key of an event from the hardware keycode
(XKB keycode, via src/input/keycodes.zig) and then remaps it through the
keyval (src/apprt/gtk/key.zig `remapKey`) so that XKB options such as
caps:escape work for keys outside the writing system. The widget does the
same in C and passes the result to `ghostty_surface_key_ex`. This script
derives the tables it needs so they never drift from Ghostty:

  - src/apprt/gtk/key.zig   `keymap`              GDK keyval -> input.Key
  - src/input/keycodes.zig  `code_to_key`         W3C code   -> input.Key
                            `raw_entries`         W3C code   -> XKB keycode
  - src/input/key.zig       `shouldBeRemappable`  writing-system keys

input.Key names are emitted as the matching ghostty_input_key_e constants
from include/ghostty.h (checked to exist).

Usage: gen-keymap.py <ghostty-src> <output.h>
"""

import re
import sys
from pathlib import Path


def c_name(zig_key: str) -> str:
    name = zig_key[4:] if zig_key.startswith("key_") else zig_key
    return "GHOSTTY_KEY_" + name.upper()


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])

    gtk_key = (src / "src/apprt/gtk/key.zig").read_text()
    keycodes = (src / "src/input/keycodes.zig").read_text()
    key_zig = (src / "src/input/key.zig").read_text()
    header = (src / "include/ghostty.h").read_text()
    c_keys = set(re.findall(r"\b(GHOSTTY_KEY_\w+)\b", header))

    km_start = gtk_key.index("const keymap: []const RawEntry")
    km_body = gtk_key[km_start : gtk_key.index("};", km_start)]
    keymap = re.findall(r"\.\{\s*gdk\.(KEY_\w+),\s*\.(\w+)\s*\}", km_body)

    ck_start = keycodes.index("const code_to_key")
    ck_body = keycodes[ck_start : keycodes.index("});", ck_start)]
    code_to_key = dict(re.findall(r'\.\{\s*"(\w+)",\s*\.(\w+)\s*\}', ck_body))

    re_body = keycodes[keycodes.index("pub const raw_entries") :]
    xkb_to_key: dict[int, str] = {}
    for m in re.finditer(
        r"\.\{\s*0x[0-9a-fA-F]+,\s*0x[0-9a-fA-F]+,\s*(0x[0-9a-fA-F]+),\s*"
        r'0x[0-9a-fA-F]+,\s*0x[0-9a-fA-F]+,\s*"(\w*)"\s*\}',
        re_body,
    ):
        xkb = int(m.group(1), 16)
        key = code_to_key.get(m.group(2))
        if key is None or xkb == 0:
            continue
        # First entry wins, matching Ghostty's linear search.
        xkb_to_key.setdefault(xkb, key)

    sr_start = key_zig.index("pub fn shouldBeRemappable")
    sr_body = key_zig[sr_start : key_zig.index("=> false", sr_start)]
    writing_system = sorted(set(re.findall(r"\.(\w+),", sr_body)))

    for key in [k for _, k in keymap] + list(xkb_to_key.values()) + writing_system:
        if c_name(key) not in c_keys:
            print(f"gen-keymap: {key} has no {c_name(key)} in ghostty.h", file=sys.stderr)
            return 1

    lines = [
        "/* Generated by linux/ghostty/widget/gen-keymap.py from the pinned",
        " * Ghostty sources. Do not edit. */",
        "#pragma once",
        "",
        "typedef struct {",
        "  guint keyval;",
        "  ghostty_input_key_e key;",
        "} TgKeyvalEntry;",
        "",
        "/* GDK keyval -> key (src/apprt/gtk/key.zig keymap). */",
        "static const TgKeyvalEntry tg_keyval_map[] = {",
    ]
    lines += [f"  {{ GDK_{kv}, {c_name(k)} }}," for kv, k in keymap]
    lines += [
        "};",
        "",
        "typedef struct {",
        "  guint16 xkb;",
        "  ghostty_input_key_e key;",
        "} TgXkbEntry;",
        "",
        "/* XKB (GDK hardware) keycode -> physical key (src/input/keycodes.zig). */",
        "static const TgXkbEntry tg_xkb_map[] = {",
    ]
    lines += [f"  {{ 0x{x:04x}, {c_name(k)} }}," for x, k in sorted(xkb_to_key.items())]
    lines += [
        "};",
        "",
        "/* Writing-system keys keep their physical identity (Key.shouldBeRemappable). */",
        "static inline gboolean",
        "tg_key_is_writing_system (ghostty_input_key_e key)",
        "{",
        "  switch (key)",
        "    {",
    ]
    lines += [f"    case {c_name(k)}:" for k in writing_system]
    lines += [
        "      return TRUE;",
        "    default:",
        "      return FALSE;",
        "    }",
        "}",
        "",
    ]
    out.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
