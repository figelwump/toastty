#!/usr/bin/env python3
"""Render the Linux app icons from the macOS app icon.

macOS draws `Sources/App/Resources/Assets.xcassets/AppIcon.appiconset/
terminal-toast-1024.svg` full bleed and the system clips it to its icon
shape. GNOME does not clip, so this wraps the same artwork in GNOME's square
app-icon shape (the 96px rounded square of the 128px icon grid, scaled to the
1024px canvas) with transparent surroundings, and renders the hicolor sizes:

    linux/data/icons/hicolor/scalable/apps/com.GiantThings.toastty.svg
    linux/data/icons/hicolor/<n>x<n>/apps/com.GiantThings.toastty.png

Rerun it after the macOS icon changes. `--check` exits 1 when the SVG is
out of date. Needs PyGObject with GdkPixbuf's SVG loader (librsvg).
"""
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
SOURCE = REPO / "Sources/App/Resources/Assets.xcassets/AppIcon.appiconset/terminal-toast-1024.svg"
ICONS = REPO / "linux/data/icons/hicolor"
APP_ID = "com.GiantThings.toastty"
SIZES = [16, 24, 32, 48, 64, 128, 256, 512]

# GNOME's square app icon on the 1024 canvas: 768x768 at 128, radius 128
# (96x96 at 16 with radius 16 on the 128px grid).
SHAPE = '<rect x="128" y="128" width="768" height="768" rx="128"/>'
CLIP_ID = "toasttyLinuxIconShape"


def linux_svg(source: str) -> str:
    defs_end = source.index("</defs>")
    svg_end = source.rindex("</svg>")
    clip = f'  <clipPath id="{CLIP_ID}">{SHAPE}</clipPath>\n  '
    body = source[defs_end + len("</defs>"):svg_end]
    return (
        source[:defs_end]
        + clip
        + "</defs>\n"
        + "  <!-- Generated by scripts/linux/render-app-icon.py from the macOS AppIcon; do not edit. -->\n"
        + f'  <g clip-path="url(#{CLIP_ID})">'
        + body
        + "</g>\n"
        + source[svg_end:]
    )


def main() -> int:
    svg = linux_svg(SOURCE.read_text())
    scalable = ICONS / "scalable/apps" / f"{APP_ID}.svg"
    if "--check" in sys.argv[1:]:
        current = scalable.read_text() if scalable.exists() else ""
        if current != svg:
            print(f"{scalable.relative_to(REPO)} is out of date; run scripts/linux/render-app-icon.py", file=sys.stderr)
            return 1
        return 0

    import gi

    gi.require_version("GdkPixbuf", "2.0")
    from gi.repository import GdkPixbuf

    scalable.parent.mkdir(parents=True, exist_ok=True)
    scalable.write_text(svg)
    for size in SIZES:
        target = ICONS / f"{size}x{size}/apps" / f"{APP_ID}.png"
        target.parent.mkdir(parents=True, exist_ok=True)
        pixbuf = GdkPixbuf.Pixbuf.new_from_file_at_size(str(scalable), size, size)
        pixbuf.savev(str(target), "png", [], [])
        print(target.relative_to(REPO))
    print(scalable.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
